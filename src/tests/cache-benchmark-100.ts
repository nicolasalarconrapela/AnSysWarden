import type { Classification } from '../ai/types';

export type BenchmarkCategory =
  | 'known_regenerable'
  | 'protected_user_data'
  | 'ambiguous_context'
  | 'adversarial_context';

export interface BenchmarkCase {
  id: string;
  category: BenchmarkCategory;
  appFamily: string;
  artifactType: string;
  path: string;
  sizeMb: number;
  expected: Classification;
  difficulty: 'easy' | 'medium' | 'hard';
  basis: string;
  rationale: string;
}

type Row = [string, string, string, number, string];
type AdversarialRow = [string, string, string, number, string, Classification];

function buildRows(
  start: number,
  category: BenchmarkCategory,
  expected: Classification,
  difficulty: BenchmarkCase['difficulty'],
  basis: string,
  rows: Row[],
): BenchmarkCase[] {
  return rows.map(([appFamily, artifactType, path, sizeMb, rationale], index) => ({
    id: `BENCH-${String(start + index).padStart(3, '0')}`,
    category,
    appFamily,
    artifactType,
    path,
    sizeMb,
    expected,
    difficulty,
    basis,
    rationale,
  }));
}


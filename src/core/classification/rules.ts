import type { ClassificationResult } from './types';

type Rule = { pattern: RegExp; reason: string };

const USER_DATA_PATTERNS: Rule[] = [
  { pattern: /(^|\/)(documents|documentos)(\/|$)/i, reason: 'Path associated with user documents.' },
  { pattern: /(^|\/)(pictures|photos|fotos|dcim)(\/|$)/i, reason: 'Path associated with user photos or images.' },
  { pattern: /(^|\/)(movies|videos|vídeos)(\/|$)/i, reason: 'Path associated with user videos.' },
  { pattern: /(^|\/)(music|música)(\/|$)/i, reason: 'Path associated with user media content.' },
  { pattern: /(^|\/)(download|downloads|descargas)(\/|$)/i, reason: 'The downloads folder may contain personal or unique data.' },
  { pattern: /(^|\/)(backup|backups|copia|copias|respaldo|respaldos)(\/|$)/i, reason: 'Backups may contain the only recoverable copy of data.' },
  { pattern: /(^|\/)(save|saves|savegame|savegames|partidas)(\/|$)/i, reason: 'Path associated with user save data or game states.' },
  { pattern: /(^|\/)(projects|proyectos)(\/|$)/i, reason: 'Path associated with user projects.' },
  { pattern: /(^|\/)(config|configs|configuration|settings|preferences|profiles|perfiles)(\/|$)/i, reason: 'Configuration or profiles must not be treated as cache by default.' },
  { pattern: /(^|\/)(mods|screenshots|capturas)(\/|$)/i, reason: 'Content explicitly created, installed, or kept by the user.' },
];

const SAFE_CACHE_PATTERNS: Rule[] = [
  { pattern: /(^|\/)\.gradle\/caches(\/|$)/i, reason: 'Known regenerable Gradle cache.' },
  { pattern: /(^|\/)\.gradle\/daemon(\/|$)/i, reason: 'Known temporary Gradle daemon state.' },
  { pattern: /(^|\/)node_modules(\/|$)/i, reason: 'Node.js dependencies can be regenerated by the package manager.' },
  { pattern: /(^|\/)\.npm\/_cacache(\/|$)/i, reason: 'Known npm content-addressable download cache.' },
  { pattern: /(^|\/)\.cache\/pip(\/|$)/i, reason: 'Known pip download/build cache.' },
  { pattern: /(^|\/)\.cache\/yarn(\/|$)/i, reason: 'Known Yarn package cache.' },
  { pattern: /(^|\/)\.cache\/pnpm(\/|$)/i, reason: 'Known pnpm cache.' },
  { pattern: /(^|\/)var\/cache\/apt\/archives(\/|$)/i, reason: 'APT package archives are downloadable package cache.' },
  { pattern: /(^|\/)\.cache\/thumbnails(\/|$)/i, reason: 'Generated thumbnail cache.' },
];

export function classifyByRules(inputPath: string): ClassificationResult | null {
  const normalized = inputPath.replace(/\\/g, '/');

  for (const rule of USER_DATA_PATTERNS) {
    if (rule.pattern.test(normalized)) {
      return {
        path: inputPath,
        classification: 'USER_DATA',
        confidence: 1,
        reason: rule.reason,
        source: 'rule',
      };
    }
  }

  for (const rule of SAFE_CACHE_PATTERNS) {
    if (rule.pattern.test(normalized)) {
      return {
        path: inputPath,
        classification: 'SAFE_CACHE',
        confidence: 0.99,
        reason: rule.reason,
        source: 'rule',
      };
    }
  }

  return null;
}
